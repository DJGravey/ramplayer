static uint8_t g_glyphs[95][FONT_H];
static uint8_t g_blank[FONT_H];
static int     g_ready;

void font_init(void)
{
    if (g_ready) return;
    for (int g = 0; g < 95; g++) {
        for (int row = 0; row < FONT_H; row++) {
            uint8_t bits = 0;
            const char *art = GLYPH_ART[g][row];
            for (int col = 0; col < FONT_W; col++)
                if (art[col] != '.' && art[col] != '\0')
                    bits |= (uint8_t)(1u << (FONT_W - 1 - col));
            g_glyphs[g][row] = bits;
        }
    }
    memset(g_blank, 0, sizeof g_blank);
    g_ready = 1;
}

const uint8_t *font_glyph(int ch)
{
    if (ch < 32 || ch > 126) return g_blank;
    return g_glyphs[ch - 32];
}

int font_text_width(const char *s, int scale)
{
    int n = (int)strlen(s);
    if (n <= 0) return 0;
    /* n cells of glyph plus the gaps between them, but no trailing gap. */
    return n * font_advance(scale) - scale;
}
